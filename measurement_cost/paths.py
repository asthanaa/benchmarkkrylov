"""Shared paths and helpers for the measurement-cost analysis (Fig. 6, Fig. S4, Table S3).

All scripts in measurement_cost/ can be run from any working directory.
"""
import csv
import json
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
RESULTS = HERE / "results"          # stored outputs (committed)
WIDTHS = RESULTS / "widths"         # exact sector widths W, one JSON per system
WORK = HERE / "work"                # Krylov matrices (*.npz), regenerated by krylov_bases.py (not committed)

FIG5_CSV = REPO / "plots/molvqe27_adapt_qrte_dt005_qrte_wmf_qkud_eps005_renyi.csv"   # data behind Fig. 5
MANIFEST = REPO / "manifests/molvqe21_fig1b_manifest.csv"                          # MolVQE-21 cases + ADAPT records

SIGMA = 1.6e-3      # chemical accuracy and target energy standard deviation (Ha)
RULES = {"W": "dt = pi/W, exact sector width", "MF": "dt = pi/W_MF, Fig. 5 protocol"}


def add_qcant():
    """Make the vendored QCANT package and the production helper scripts importable."""
    for p in (REPO / "vendor/QCANT", REPO / "scripts/Mushir_script"):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    # QCANT/_version.py is generated when QCANT is installed and is git-ignored, so a fresh clone
    # imports the vendored copy with a placeholder version (or run: pip install -e vendor/QCANT).
    if not (REPO / "vendor/QCANT/QCANT/_version.py").exists() and "QCANT._version" not in sys.modules:
        stub = types.ModuleType("QCANT._version")
        stub.__version__ = "vendored"
        sys.modules["QCANT._version"] = stub


def fig5_rows(series="qrte_mf"):
    """Rows of the Fig. 5 data table for one series, keyed by case_id."""
    return {r["case_id"]: r for r in csv.DictReader(open(FIG5_CSV)) if r["series"] == series}


def payload(case_id):
    """Hamiltonian payload exactly as used by the QRTE-T2 production runs of Fig. 5 (QCANT qulacs_accel).

    Returns (payload, summary) where summary is the production run's summary.json.
    """
    add_qcant()
    from QCANT import qulacs_accel as qa
    from compute_initial_overlap import _payload_from_cache_path
    summ = json.load(open(REPO / fig5_rows()[case_id]["summary_path"]))
    cache = summ["hamiltonian_cache_path"]
    cache = REPO / cache[cache.index("hamiltonian_cache/"):]
    return _payload_from_cache_path(cache, hamiltonian_cutoff=1e-20, qa=qa), summ


def read_csv(path):
    return {r["case_id"]: r for r in csv.DictReader(open(path))} if Path(path).exists() else {}


def write_csv(path, rows):
    """Write rows (list of dicts) sorted by case_id."""
    rows = sorted(rows, key=lambda r: r["case_id"])
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def npz_path(rule, case_id):
    return WORK / rule / f"{case_id}.npz"
